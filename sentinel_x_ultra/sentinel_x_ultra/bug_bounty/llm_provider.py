    def _fallback_response(self, reason: str) -> str:
        """Return a structured fallback response when LLM is unavailable."""
        return f"[LLM Fallback: {reason}]"

    def _parse_json_response(self, response: str) -> dict[str, Any]:
        """Extract JSON from an LLM response, handling markdown fences and extra text."""
        if not response:
            return {}

        # Remove markdown code fences
        cleaned = re.sub(r'```(?:json)?\s*\n?', '', response).strip()

        # Try to find JSON object/array boundaries
        for start_char, end_char in [('{', '}'), ('[', ']')]:
            start_idx = cleaned.find(start_char)
            if start_idx >= 0:
                end_idx = cleaned.rfind(end_char)
                if end_idx > start_idx:
                    json_str = cleaned[start_idx:end_idx + 1]
                    try:
                        return json.loads(json_str)
                    except json.JSONDecodeError:
                        continue

        # Last resort: try parsing the whole cleaned string
        try:
            return json.loads(cleaned)
        except json.JSONDecodeError:
            return {"raw_response": response[:500]}

    def truncate_for_context(self, text: str, max_chars: int = 4000) -> str:
        """Truncate text to fit within LLM context limits."""
        if len(text) <= max_chars:
            return text
        return text[:max_chars] + f"\n... [truncated, {len(text) - max_chars} more chars]"


