"""
LLM PROVIDER — Multi-Model AI Abstraction Layer for Bug Bounty Agents.

Provides a unified interface for all 10 agents to call LLMs for reasoning,
analysis, and decision-making. Supports multiple providers:
  - OpenAI GPT-4o (primary reasoning)
  - Anthropic Claude 3.5 Sonnet (analysis & reporting)
  - Local Ollama (offline/air-gapped fallback)

Architecture:
  LLMProvider (interface)
    ├── OpenAILLM     → api.openai.com
    ├── ClaudeLLM     → api.anthropic.com
    └── OllamaLLM     → localhost:11434

Usage by agents:
  provider = LLMProvider.get_default()
  analysis = await provider.analyze_finding(finding)
  severity = await provider.score_cvss(evidence)
"""

