# ── Configuration ───────────────────────────────────────────────────────────

class LLMProviderType(str, Enum):
    OPENAI = "openai"
    CLAUDE = "claude"
    OLLAMA = "ollama"
    AUTO = "auto"  # Try providers in order of capability


@dataclass
class LLMConfig:
    """Configuration for an LLM provider."""
    provider_type: LLMProviderType = LLMProviderType.AUTO
    model: str = ""
    api_key: str = ""
    api_base: str = ""
    temperature: float = 0.1  # Low temp for deterministic security analysis
    max_tokens: int = 4096
    timeout_seconds: int = 60

    @classmethod
    def from_env(cls) -> "LLMConfig":
        """Load config from environment variables with sensible defaults."""
        # Try OpenAI first (most capable)
        if os.environ.get("OPENAI_API_KEY"):
            return cls(
                provider_type=LLMProviderType.OPENAI,
                model=os.environ.get("OPENAI_MODEL", "gpt-4o"),
                api_key=os.environ["OPENAI_API_KEY"],
                api_base=os.environ.get("OPENAI_API_BASE", ""),
            )
        # Then Claude
        if os.environ.get("ANTHROPIC_API_KEY"):
            return cls(
                provider_type=LLMProviderType.CLAUDE,
                model=os.environ.get("ANTHROPIC_MODEL", "claude-3-5-sonnet-20241022"),
                api_key=os.environ["ANTHROPIC_API_KEY"],
                api_base=os.environ.get("ANTHROPIC_API_BASE", ""),
            )
        # Fallback to Ollama (local)
        return cls(
            provider_type=LLMProviderType.OLLAMA,
            model=os.environ.get("OLLAMA_MODEL", "llama3.2"),
            api_base=os.environ.get("OLLAMA_API_BASE", "http://localhost:11434"),
        )


